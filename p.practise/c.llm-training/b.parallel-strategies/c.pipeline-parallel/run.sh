#!/bin/bash
# ============================================================
# 实验: c.pipeline-parallel
# 说明: PP、气泡、1F1B 调度
# 模块: p.practise/c.llm-training  LLM 训练
# ============================================================
# 【第一性原理】
# 流水并行(PP):模型太深放不下,把不同层分到不同卡,数据像流水线一样流过各卡。
# 朴素 GPipe:先把一批 micro-batch 全前向过完再全反向→中间有大量"气泡"(卡在空等)。
# 1F1B:交错前向反向,让每卡尽早开始反向,减少气泡、省显存(同时持有的激活更少)。
# 气泡比例≈(P-1)/(M+P-1)(P=阶段数,M=micro-batch 数),M 越大气泡越小。本实验模拟调度并算气泡。
# ============================================================
set -euo pipefail
if ! python3 -c "import numpy" 2>/dev/null; then
  echo "未检测到 numpy,正在安装..."; python3 -m pip install --quiet numpy || { echo "请手动: pip install numpy"; exit 1; }
fi
echo "============================================================"
echo " 实验: 流水并行 / 气泡 / 1F1B 调度"
echo "============================================================"
python3 <<'PY'
import numpy as np
# 气泡比例
def bubble(M,P): return (P-1)/(M+P-1)
print("【1】气泡比例=(P-1)/(M+P-1):P=阶段数,M=micro-batch 数")
for P in [4,8]:
    for M in [4,16,64]:
        print(f"  P={P}, M={M:<3}: 气泡={bubble(M,P)*100:.1f}%  (M越大气泡越小)")
print("  解读:micro-batch 越多,流水线越满,气泡越小;但太少时阶段间空等严重。")

# 2 朴素 GPipe vs 1F1B 持有激活数
print("\n【2】朴素 GPipe vs 1F1B:同时持有的 micro-batch 激活数(影响显存)")
P=4; M=8
gpipe_max=M              # GPipe:前向全做完才反向,同时持有 M 个激活
onef1b_max=P             # 1F1B:稳态后每卡只持有约 P 个激活
print(f"  P={P}, M={M}: GPipe 持有峰值≈{gpipe_max}, 1F1B 持有峰值≈{onef1b_max}")
print("  解读:1F1B 让每卡尽早反向释放激活,峰值激活数从 M 降到≈P,大幅省显存,大模型必备。")

# 3 调度直觉(文字时间线)
print("\n【3】1F1B 调度直觉(阶段0最先、阶段3最后):")
print("  阶段0: F0 F1 F2 F3 B0 F4 B1 F5 B2 ...  (前向/反向交错)")
print("  阶段3: ........ F0 F1 F2 F3 B0 B1 B2 ...  (要等前面流过来才能前向,再反向)")
print("  解读:靠交错前向反向压缩气泡、降显存;气泡在首尾(暖机/排空)不可避免。")
PY
echo "============================================================"
cat <<'EOF'
【结论与进阶】
- 小白:流水并行把不同层放不同卡,数据像流水线流过;气泡=空等,加 micro-batch 可减少;1F1B 交错调度省显存。
- 熟手:气泡=(P-1)/(M+P-1);1F1B 把峰值激活从 M 降到 P;交错式 PP(Interleaved)进一步减气泡;
  PP 通信量小(层边界传激活),适合跨节点;与 TP/DP 组合成 3D 并行。
- 延伸:把 M 从8调到32看气泡下降;对比 GPipe 与 1F1B 的显存峰值。
EOF
echo "============================================================"
