python3 <<'PY'
import numpy as np
rng = np.random.default_rng(42)

def step(n, t, title):
    print(f"\n{'='*60}\n【步骤 {n}/{t}】{title}\n{'='*60}")
def why(t):
    print("\n--- 我们要做什么 & 为什么要这么做 ---")
    for l in t.strip().splitlines(): print("  "+l)
def res(t):
    print("\n--- 运行结果 ---")
    for l in t.strip().splitlines(): print("  "+l)
def meaning(t):
    print("\n--- 结果解读(这说明了什么)---")
    for l in t.strip().splitlines(): print("  "+l)
T=4

# ============================================================
step(1,T,"采样两种分布,用文本直方图看形状")
why("""
分别从均匀分布 U(0,1) 和正态分布 N(0,1) 各采样 5000 次,画文本直方图。
为什么:分布描述随机变量的"取值规律"。直方图能直观看出形状——
均匀=平的(每个值等可能),正态=钟形(中间多两头少)。
很多自然现象(测量误差、身高)近似正态,这是建模的常用假设。""")
def hist(samples, bins=15, width=40):
    lo, hi = samples.min(), samples.max()
    edges = np.linspace(lo, hi, bins+1)
    counts, _ = np.histogram(samples, bins=edges); m = counts.max()
    out=[]
    for i,c in enumerate(counts):
        out.append(f"  [{edges[i]:5.2f},{edges[i+1]:5.2f}) {'█'*int(c/m*width)} {c}")
    return "\n".join(out)
u = rng.uniform(0,1,5000); nd = rng.standard_normal(5000)
res("均匀分布 U(0,1):\n"+hist(u)+"\n\n正态分布 N(0,1):\n"+hist(nd))
meaning("""
均匀分布的柱子高低差不多(平的)——每个区间概率相近。
正态分布中间高、两边低(钟形)——取值集中在 0 附近,极端值少。
→ 训练数据的分布形状,往往决定了该用什么模型/损失函数。""")

# ============================================================
step(2,T,"期望与方差:样本估计随样本量趋近理论值")
why("""
从 N(0,1) 采样不同数量(100/1000/100000),算样本均值和方差。
为什么:期望 E[X] 是分布的"重心"(理论均值),方差是"波动大小"。
大数定律告诉我们:样本越多,样本均值越接近真实期望。
这就是"数据越多,估计越准"——也是模型训练需要大数据的根基。""")
out=[]
for n in [100, 1000, 100000]:
    x = rng.standard_normal(n)
    out.append(f"  采样 {n:>6} 次: 样本均值={x.mean():+.4f}  样本方差={x.var():.4f}  (理论 0 / 1)")
res("\n".join(out))
meaning("""
样本越多,均值越贴近 0、方差越贴近 1(理论值)。
100 次时偏差明显,100000 次时几乎吻合。
→ 这就是为什么 batch 越大梯度估计越稳,也是大数据训练的理论依据。""")

# ============================================================
step(3,T,"大数定律:累计均值的收敛轨迹")
why("""
采样 10000 个 N(0,1) 的数,看"前 N 个的累计均值"如何随 N 变化。
为什么:直观感受"一开始剧烈抖动,越往后越稳定地贴近期望 0"。
模型训练 loss 下降也是类似——随着样本累积,噪声被平均掉,趋势浮现。""")
x = rng.standard_normal(10000); cum = np.cumsum(x)/np.arange(1,len(x)+1)
out=[]
for st in [10,100,1000,10000]:
    out.append(f"  前 {st:>5} 个样本的累计均值 = {cum[st-1]:+.4f}")
res("\n".join(out))
meaning("""
前 10 个均值 -0.19(偏离明显),前 10000 个 +0.007(几乎为 0)。
样本少时随机波动大,样本多时均值收敛到真实期望。
→ 深度学习的"梯度"是全数据梯度的随机估计,batch 大=估计准但慢,batch 小=快但抖。""")

# ============================================================
step(4,T,"贝叶斯定理:阳性就一定患病吗?")
why("""
假设人群患病率 1%,检测敏感度 99%(真患者阳性率),特异度 95%(健康人阴性率)。
算"检测阳性时真正患病的概率"。
为什么:贝叶斯定理用"先验信念 + 新证据"更新认知。直觉常被误导——
检测"准确率 99%"听起来很高,但罕见病的假阳性会占多数。""")
prior,sens,spec = 0.01,0.99,0.95
p_pos = sens*prior + (1-spec)*(1-prior)
post = sens*prior/p_pos
res(f"""先验 P(患病)       = {prior}
似然 P(阳性|患病)  = {sens}
全概率 P(阳性)     = {p_pos:.4f}  (真患者阳性 + 健康人假阳性之和)
后验 P(患病|阳性)  = {post:.4f}  → 仅 {post*100:.1f}%""")
meaning(f"""
检测阳性,但真正患病的概率只有 {post*100:.0f}%!原因:患病率太低(1%),
即便假阳率只有 5%,健康人的假阳性数量也远超真患者。
→ 贝叶斯的核心:先验很重要。罕见事件哪怕检测准,阳性也多半是虚惊。
→ AI 里:正则化=给参数加"先验";贝叶斯优化=用历史观测更新对最优值的信念。
→ 试一试:运行 demo.py --prior 0.1 看提高患病率后后验怎么变。""")
PY

