# 【第一性原理】
# VGG:用堆叠的 3×3 小卷积代替大卷积,统一简洁但参数量巨大(全连接大头)。
# Inception:同一层并行多种尺寸的卷积(1×1、3×3、5×5)+池化,多尺度特征一次抓全。
# ResNet:引入残差连接 x+F(x),让梯度能直通,使几十上百层可训练——深度的关键突破。
# 本实验对比三者的参数量思想,并用数值展示残差如何保住深层梯度。
# ============================================================
set -euo pipefail
if ! python3 -c "import numpy" 2>/dev/null; then
  echo "未检测到 numpy,正在安装..."; python3 -m pip install --quiet numpy || { echo "请手动: pip install numpy"; exit 1; }
fi
echo "============================================================"
echo " 实验: 经典骨干 / VGG / Inception / ResNet 残差"
echo "============================================================"
python3 <<'PY'
import numpy as np
np.set_printoptions(precision=3, suppress=True)

# 1 参数量思想对比
print("【1】三种骨干的参数量思想(示意,单层视角):")
# VGG: 3×3 conv, 通道从64到512, 末端3个4096全连接
vgg_conv=3*3*128*128
vgg_fc=7*7*512*4096+4096*4096+4096*1000
print(f"  VGG: 一层3×3卷积(128→128)={vgg_conv}; 末端全连接≈{vgg_fc:,}(全连接是参数大头)")
# Inception: 并行 1x1,3x3,5x5 各路,用 1x1 先降通道省参数
incep=3*3*64*128 + 5*5*64*32
print(f"  Inception: 并行多尺度卷积≈{incep}(用1×1先降通道再卷,省参数)")
# ResNet: 残差块,用全局平均池化代替大全连接
resnet_block=3*3*64*64*2
print(f"  ResNet: 一个残差块(两层3×3)={resnet_block}; 用全局平均池化去掉大全连接")
print("  解读:VGG 简洁但全连接参数巨大;Inception 多尺度+1×1降维省参数;ResNet 去大全连接+残差,能训更深。")

# 2 残差连接保梯度
print("\n【2】残差连接如何保住深层梯度(数值模拟):")
def plain_grad(L,jac=0.9):
    g=1.0
    for _ in range(L): g*=jac      # 普通网络:梯度=各层雅可比连乘(<1→指数消失)
    return g
def res_grad(L):                    # 残差:恒等支路让梯度有直通通道,≈1 不随深度衰减
    return 1.0
for L in [10,30,100]:
    print(f"  深度 L={L}: 普通网络梯度={plain_grad(L):.2e}  残差网络梯度={res_grad(L):.2f}")
print("  解读:普通网络梯度=各层雅可比连乘,随深度指数消失;残差的恒等支路让梯度≈1 直通,深层不消失。")
print("        → 这就是 ResNet 能训上百层、而普通网络几十层就训不动的根本原因。")

# 3 Inception 多尺度直觉
print("\n【3】Inception 多尺度:同一层同时用不同大小核抓不同尺度特征")
for name,ksize in [("1×1 细节",1),("3×3 局部",3),("5×5 广域",5)]:
    print(f"  {name}:核{ksize}×{ksize}  → 并行输出拼接成多尺度特征")
print("  解读:不同尺寸核关注不同范围的纹理,拼接后模型同时拥有细粒度和粗粒度信息。")
PY
echo "============================================================"
cat <<'EOF'
【结论与进阶】
- 小白:VGG 堆小卷积简洁但参数大;Inception 同层多尺度并行抓不同大小特征;ResNet 残差让梯度直通、能训很深。
- 熟手:残差 d(x+F)/dx=1+F' 的"1"是深网可训的数学根因;1×1 卷积是降维/升维的参数利器;
  全局平均池化取代大全连接大幅减参数;后续 DenseNet、EfficientNet 都建立在这些思想之上。
- 延伸:把残差因子从0.6调到0.9看梯度差异;思考为何残差学"残差F(x)"比直接学H(x)容易。
