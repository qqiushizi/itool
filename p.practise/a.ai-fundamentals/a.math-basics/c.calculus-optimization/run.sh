echo "# 实验 3: 导数 / 梯度 / 链式法则 / 梯度下降"
echo "# 每步: 【做什么&为什么】→【结果】→【结果解读】"
echo "############################################################"

python3 <<'PY'
import numpy as np

def step(n,t,title): print(f"\n{'='*60}\n【步骤 {n}/{t}】{title}\n{'='*60}")
def why(t):
    print("\n--- 我们要做什么 & 为什么要这么做 ---")
    for l in t.strip().splitlines(): print("  "+l)
def res(t):
    print("\n--- 运行结果 ---")
    for l in t.strip().splitlines(): print("  "+l)
def meaning(t):
    print("\n--- 结果解读(这说明了什么)---")
    for l in t.strip().splitlines(): print("  "+l)
T=4

# ============================================================
step(1,T,"导数:数值近似 vs 解析公式")
why("""
对 f(x)=x^2,在 x=3 处分别用解析公式(2x)和数值差分求导,对比。
为什么:导数是函数在某点的"瞬时变化率"=切线斜率。
不会求导时,可用"附近两点连线斜率"近似(数值差分)。
深度学习框架的"梯度检验"就用这招验证自定义算子的反向实现是否正确。""")
def f(x): return x**2
def df(x): return 2*x
x0,h = 3.0,1e-5
num = (f(x0+h)-f(x0-h))/(2*h)
res(f"""f(x) = x^2,  在 x = {x0}
  解析导数 f'(x)=2x       = {df(x0)}
  数值导数(中心差分)     = {num:.6f}
  两者误差                = {abs(df(x0)-num):.2e}""")
meaning("""
数值导数和解析导数几乎一致(误差极小)。
→ 反向传播手写容易出错,用数值梯度对比解析梯度,是排查 bug 的标准手段。
→ 直觉:导数>0 函数在涨,导数<0 在跌;找最小值就往导数为0的方向走。""")

# ============================================================
step(2,T,"梯度下降:求 f(x,y)=x^2+3y^2 的最小值")
why("""
从起点 (4,4) 出发,每步沿"负梯度"方向走一小步,看 loss 如何下降。
为什么:梯度=各变量偏导组成的向量,指向"上升最快"的方向。
沿负梯度走=下降最快。这就是神经网络训练的核心动作。
学习率决定每步走多远——太大发散,太小太慢。""")
def loss(p): return p[0]**2 + 3*p[1]**2
def grad(p): return np.array([2*p[0], 6*p[1]])
p = np.array([4.0,4.0]); lr=0.1
out=[f"  起点 = {p.tolist()}, loss = {loss(p):.3f}"]
for i in range(1,6):
    g=grad(p); p=p-lr*g
    out.append(f"  步{i}: grad={g.tolist()}, 新位置={p.round(4).tolist()}, loss={loss(p):.4f}")
res("\n".join(out))
meaning("""
每步 loss 都在下降,位置逐渐逼近最小值 (0,0)。
注意 y 方向梯度大(系数3),下降更快——梯度下降会优先纠正"陡"的方向。
→ 这就是优化器的工作:反复算梯度、走一步、再算梯度,直到 loss 不再下降。""")

# ============================================================
step(3,T,"链式法则:复合函数求导(反向传播原理)")
why("""
设 y=f(g(x)),g(x)=x^2,f(g)=3g+1,即 y=3x^2+1。用链式法则求 dy/dx。
为什么:反向传播就是链式法则的工程化——从输出往输入,
逐层把"总误差对各参数的导数"乘出来。理解链式法则=理解反向传播。
梯度爆炸/消失的本质,就是链式法则连乘时每层放大或缩小。""")
x=2.0; g=x**2; y=3*g+1
df_dg=3.0; dg_dx=2*x; dy_dx=df_dg*dg_dx
res(f"""g(x)=x^2={g},  f(g)=3g+1 -> y={y}
  df/dg = {df_dg}  (f 对 g 的导数)
  dg/dx = {dg_dx}  (g 对 x 的导数)
  dy/dx = df/dg * dg/dx = {df_dg} * {dg_dx} = {dy_dx}  (解析 6x={6*x})""")
meaning(f"""
链式法则:总导数 = 各层导数连乘 = {dy_dx},与解析结果 6x={6*x} 一致。
→ 神经网络层数深时,梯度 = 很多个导数连乘。若每层>1→梯度爆炸;每层<1→梯度消失。
→ 这就是为什么深层网络难训练,以及 ResNet 残差连接(加法不连乘)能缓解梯度消失。""")

# ============================================================
step(4,T,"学习率:太大发散,太小太慢")
why("""
用不同学习率(0.05/0.1/0.33)各跑 20 步梯度下降,看结果。
为什么:学习率是训练最重要的超参数。太大会一步跨过谷底弹到更高(loss 越走越大=发散);
太小虽然稳但收敛极慢,浪费算力。调参第一步往往就是调学习率。""")
out=[]
for lr in [0.05,0.1,0.33]:
    p=np.array([4.0,4.0])
    for _ in range(20): p=p-lr*grad(p)
    if np.any(np.abs(p)>1e3): tag="发散! (loss 越来越大)"
    else: tag=f"收敛到 {p.round(4).tolist()}"
    out.append(f"  lr={lr:<5}: 20步后 {tag}")
res("\n".join(out))
meaning("""
lr=0.05:步子小,20步还没收敛到 0(慢)。
lr=0.1:恰到好处,接近最小值。
lr=0.33:步子太大,在谷底反复横跳甚至发散。
→ 学习率要不大不小。实战常用 warmup+cosine 衰减:开始小步试探,中间大步快跑,末尾小步精调。
→ 试一试:运行 demo.py --lr 0.3 --steps 50,自己体验不同学习率的收敛/发散。""")
PY

echo ""
