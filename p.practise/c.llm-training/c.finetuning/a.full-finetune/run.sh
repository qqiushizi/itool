#!/bin/bash
# ============================================================
# 实验: a.full-finetune
# 说明: 全参微调显存/算力分析
# 模块: p.practise/c.llm-training  LLM 训练
# ============================================================
# 【第一性原理】
# 全参微调:解冻所有参数,用下游数据更新整个模型。效果上限高,但成本惊人:
#  显存=参数(2φ)+梯度(2φ)+优化器(Adam ~8φ)+激活≈12φ 起,7B 模型单卡就要 ~80GB+。
#  算力≈6·N·D(同预训练量级,因为每参数都要更新)。
# 所以全参微调通常需要多卡+ZeRO/并行,且容易过拟合小数据。本实验建模显存/算力,对比与 PEFT 的差距。
# ============================================================
set -euo pipefail
if ! python3 -c "import numpy" 2>/dev/null; then
  echo "未检测到 numpy,正在安装..."; python3 -m pip install --quiet numpy || { echo "请手动: pip install numpy"; exit 1; }
fi
echo "============================================================"
echo " 实验: 全参微调 / 显存算力 / 与 PEFT 对比"
echo "============================================================"
python3 <<'PY'
import numpy as np
# 显存建模(单位 φ×字节):参数2 + 梯度2 + Adam优化器8 + 激活(随seq/batch)
def full_mem(phi,act=4): return (2+2+8+act)*phi/1e9       # 全参
def peft_mem(phi,r=0.01,act=4): return (2+2*r+8*r+act)*phi/1e9  # 只训 r 比例参数
print("【1】全参微调显存(参数+梯度+Adam优化器+激活):")
for phi in [1e9,7e9,70e9]:
    print(f"  {phi:.0e} 参数: 全参微调单卡≈{full_mem(phi):.0f} GB")
print("  解读:Adam 优化器状态(8φ)是大头;7B 全参微调单卡就需 ~80GB,70B 需数百 GB→必须多卡+ZeRO。")

# 2 算力对比
print("\n【2】算力:全参更新所有参数 vs PEFT 只更新一小部分")
for phi,frac in [(7e9,1.0),(7e9,0.005)]:
    flops=6*phi*1e9*frac   # 1B tokens 微调
    print(f"  7B, 更新比例={frac*100:.1f}%: 算力≈{flops/1e18:.2f} EFLOPs")
print("  解读:全参微调算力正比于全部参数;PEFT 只训 <1% 参数,算力和显存大幅下降。")

# 3 过拟合风险
print("\n【3】全参微调的过拟合风险(小数据 + 大模型):")
print("  全参更新数百万~数十亿参数,而下游数据往往只有几千~几万条→极易过拟合、灾难性遗忘。")
print("  解读:全参效果上限高但需大数据+正则;小数据场景 PEFT(LoRA 等)更稳、更省,是主流。")
PY
echo "============================================================"
cat <<'EOF'
【结论与进阶】
- 小白:全参微调解冻所有参数,效果高但显存/算力巨大(Adam 优化器是大头),小数据易过拟合。
- 熟手:全参显存≈12φ+;7B 需多卡+ZeRO;算力正比于全部参数;
  灾难性遗忘靠低 LR、数据混合、EWC 缓解;大数据/高上限任务才值得全参,否则用 PEFT。
- 延伸:把激活项调大看长序列显存;对比全参与 LoRA 的可训参数比例。
EOF
echo "============================================================"
