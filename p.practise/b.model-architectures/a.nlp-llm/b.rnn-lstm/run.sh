# ============================================================
# 实验: b.rnn-lstm
# 说明: 序列建模、门控、梯度消失/爆炸模拟
# 模块: p.practise/b.model-architectures  模型架构
# ============================================================
# 【第一性原理】
# RNN 处理序列:每步用"当前输入+上一步隐状态"算新隐状态 h_t=f(x_t,h_{t-1}),把历史信息传下去。
# 但 h_t 对 h_{t-1} 的雅可比连乘 T 次:因子>1→梯度爆炸,<1→梯度消失,长序列记不住远处。
# LSTM 用遗忘门/输入门/输出门控制信息流,门是可学习的开关,让梯度有"高速公路"直通,缓解长依赖。
# 本实验模拟 RNN 前向 + 梯度连乘衰减/爆炸,并演示 LSTM 门如何保梯度。
# ============================================================
set -euo pipefail
if ! python3 -c "import numpy" 2>/dev/null; then
  echo "未检测到 numpy,正在安装..."; python3 -m pip install --quiet numpy || { echo "请手动: pip install numpy"; exit 1; }
fi
echo "============================================================"
echo " 实验: RNN / 序列建模 / 梯度消失爆炸 / LSTM 门控"
echo "============================================================"
python3 <<'PY'
import numpy as np
np.set_printoptions(precision=4, suppress=True)
def sig(z): return 1/(1+np.exp(-z))

# 1 RNN 前向:沿序列传隐状态
print("【1】RNN 前向:h_t = tanh(W_x·x_t + W_h·h_{t-1} + b)")
Wx=np.array([[0.8]]); Wh=np.array([[0.9]]); b=np.array([0.0])
xs=np.array([1.0,0.5,-0.3,0.7,1.2])
h=0.0; hist=[]
for xt in xs:
    h=np.tanh(Wx[0,0]*xt+Wh[0,0]*h+b[0]); hist.append(h)
print(f"  输入序列 = {xs.tolist()}")
print(f"  隐状态序列 = {np.round(hist,4).tolist()}")
print("  解读:每步把当前输入和上一步记忆融合;h 既反映当前也带历史,所以能建模序列。")

# 2 梯度连乘:因子>1爆炸,<1消失
print("\n【2】梯度沿时间连乘(雅可比因子 ≈ Wh·(1-h²)):")
for factor,label in [(1.5,">1 爆炸"),(0.7,"<1 消失"),(1.0,"=1 恒定")]:
    g=factor**20
    print(f"  因子={factor}({label}):连乘20步后梯度 = {g:.3e}")
print("  解读:RNN 的梯度是各步雅可比的连乘,因子偏离1会让梯度指数级爆炸或消失→长序列学不动。")

# 3 LSTM 门:让梯度有近恒定通道
print("\n【3】LSTM 用门控保护长程梯度:")
c=1.0; f_gate=0.99            # 可学的遗忘门选择"记住"(≈1),梯度=遗忘门连乘
for t in range(20):
    c=c*f_gate                  # 细胞状态乘遗忘门(近恒定→梯度高速公路)
print(f"  遗忘门≈{f_gate} 时,细胞状态经20步 = {c:.4f}  (几乎不衰减→长程梯度保住)")
print(f"  对比 RNN 因子0.7 连乘20步 = {0.7**20:.2e}  (早已消失)")
print("  解读:LSTM 的细胞状态 c 靠加法更新(不是乘法),遗忘门≈1时梯度几乎不衰减→'高速公路'传长依赖。")
print("        三个门(遗忘/输入/输出)都是可学的 sigmoid 开关,决定记什么、忘什么、输出什么。")
PY
echo "============================================================"
cat <<'EOF'
【结论与进阶】
- 小白:RNN 靠隐状态把序列历史传下去;但梯度连乘会爆炸或消失,长序列记不住远处;
  LSTM 用门控(遗忘/输入/输出)给梯度一条近恒定通道,缓解长依赖。
- 熟手:梯度爆炸靠梯度裁剪(clip)压制,梯度消失靠 LSTM/GRU 门控 + 残差缓解;
  GRU 合并门更省参数;但 RNN 串行计算慢,Transformer 用注意力并行取代了它。
- 延伸:把序列长度从5加到50看 RNN 隐状态是否还能反映第一个输入;把遗忘门设为0.5看记忆衰减。
EOF
echo "============================================================"
