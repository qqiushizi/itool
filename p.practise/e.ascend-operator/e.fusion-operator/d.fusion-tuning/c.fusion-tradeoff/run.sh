#!/bin/bash
# ============================================================
# 实验: c.fusion-tradeoff
# 说明: 融合 vs 不融合 的性能/显存/精度权衡决策
# 模块: p.practise 第一性原理学习实验
# ============================================================
# 【第一性原理】
# 融合不是银弹, 要权衡 3 个维度:
#   1. 性能: 融合快, 但有时不融更快 (调度问题)
#   2. 显存: 融合省, 但开发周期长
#   3. 精度: 融合可能掉, 需对齐
# 决策树:
#   - 推理 + 大 batch: 优先融合 (省显存)
#   - 训练 + 复杂算子: 谨慎融合 (精度风险)
#   - 调试阶段: 不融合 (易调试)
#   - 性能瓶颈算子: 融合 (值得投入)
# 不适合融合的场景:
#   - 算子间有依赖但无复用 (ReLU 跟 matmul)
#   - 算子形状差异大 (Linear 2D, Softmax 1D)
#   - 精度要求高 (训练 Softmax+CE)
# ============================================================
set -euo pipefail
echo "############################################################"
echo "# 实验: c.fusion-tradeoff | 融合 vs 不融合权衡决策"
echo "############################################################"

python3 <<'PYEOF'
def hdr(n,total,t): print(f"\n{'='*60}\n【步骤 {n}/{total}】{t}\n{'='*60}")
def why(s): print("\n--- 做什么 & 为什么 ---\n  "+s.replace("\n","\n  "))
def res(s): print("\n--- 结果 ---\n  "+s.replace("\n","\n  "))
def mea(s): print("\n--- 解读 ---\n  "+s.replace("\n","\n  "))
TOTAL = 4

# --- 1. 融合收益的 4 个来源 ---
hdr(1,TOTAL,"融合收益的 4 个来源")
why("""融合快, 来自 4 个节省:
  1. Kernel 启动开销: 1 个 vs N 个 (每 kernel ~10us)
  2. 中间结果 HBM 读写: 不写出, 不读回
  3. 算子间调度: 无空隙, 连续算
  4. 缓存复用: 数据在 UB/L1, 不去 HBM
但融合也有代价:
  1. 编译时间 + 重编风险
  2. 调试复杂 (1 个 op 错 = 整链路错)
  3. 维护成本 (改 1 个 op 都要重测)""")
out = ["  收益来源         节省量           前提条件"]
out.append("  Kernel 启动       ~10us * (N-1)   N 个紧邻 op")
out.append("  HBM 读写         N-1 次 buffer   算子间有中间结果")
out.append("  调度空隙         ~5-20us         短 kernel 间")
out.append("  缓存复用         视情况          数据有复用")
out.append("  累加器复用       matmul 链多省    多个 matmul 累加")
res("\n".join(out))
mea("""4 个来源的优先级:
  1. Kernel 启动 (最常见, 易得)
  2. HBM 读写 (中等, 主要收益)
  3. 调度空隙 (小 kernel 链多)
  4. 缓存复用 (难, 需手工调)
不同算子收益不同:
  - Linear+ReLU: 主要省 HBM 读写
  - MHA: 主要省 kernel 启动
  - Conv+BN+ReLU: 主要省累加器复用""")

# --- 2. 不适合融合的场景 ---
hdr(2,TOTAL,"不适合融合的场景")
why("""以下情况不融合更好:""")
out = ["  场景                不融合原因                替代方案"]
out.append("  形状差异大          tiling 难统一              拆 2 个 kernel")
out.append("  算子间无复用        纯串行, 无中间 buffer      框架自动调度")
out.append("  精度要求极高        算子顺序敏感              不融, 手动顺序")
out.append("  算子分支            if/else 内不同            不融, 跑 2 次")
out.append("  调试期              难定位                    不融, 单独测")
out.append("  op 1 极小           启动开销大于算             不融, 框架 batch")
out.append("  动态 shape          tiling 难动态              不融, 框架动态")
res("\n".join(out))
mea("""融合的 反模式 (anti-pattern):
  1. 简单 1+1 融 (Add+ReLU) 收益小, 维护成本高
  2. 形状 mismatch (Linear 2D + Softmax 1D) 难写
  3. 强制融合所有算子 (过度优化, 难维护)
  4. 在调试期融合 (错难定位)
  5. 算子间数据流不清 (不一定真能省)""")

# --- 3. 决策树 ---
hdr(3,TOTAL,"是否融合:决策树")
why("""工程上判断 融合 vs 不融合, 走决策树:""")
out = ["  决策点              是 ->          否 ->"]
out.append("  1. 性能瓶颈 op?     融合            暂不融")
out.append("  2. 算子紧邻?        融合            暂不融")
out.append("  3. shape 匹配?     融合            不融")
out.append("  4. 精度影响?       测后再定       不融 (有风险)")
out.append("  5. 调试期?         不融 (写完再融) 融合")
out.append("  6. 维护成本?       收益 > 2x 融   收益 < 1.5x 不融")
out.append("  7. 团队熟悉?       熟悉 融         不熟 不融 (避免坑)")
res("\n".join(out))
mea("""决策树实战:
  1. 先不融, 用框架默认 (跑通业务)
  2. profile 找 hot op (top 5)
  3. 评估 hot op 融合收益 (>1.3x 才做)
  4. 写融合算子, 测精度 (max_rel < 1e-3)
  5. A/B 测试 (性能 + 精度 + 业务指标)
  6. 上线, 监控 (回归)
注意: 不要全模型融合, 选 hot spot 就够""")

# --- 4. 量化收益对比 (伪) ---
hdr(4,TOTAL,"融合收益量化对比")
why("""用伪数据量化 5 种典型算子组合的融合收益:""")
out = ["  算子组合            kernel 数  节省启动  HBM 节省  总加速  融合建议"]
combos = [
    ("Linear+ReLU",         2, 1, 1, 1.0, 1.0, 1.30, "强推"),
    ("Linear+LayerNorm",    3, 1, 2, 1.0, 1.5, 1.50, "推"),
    ("Softmax+CE",         2, 1, 1, 1.0, 1.0, 1.20, "可"),
    ("MHA(qkv) + Softmax", 5, 1, 4, 1.0, 2.0, 2.50, "强推"),
    ("Conv+BN+ReLU",       3, 1, 2, 1.0, 1.5, 1.80, "推"),
    ("Concat+Split (逆向)",2, 1, 0, 1.0, 0.0, 1.05, "不融"),
    ("Add+Mul+Add+Mul",   4, 1, 3, 1.0, 1.8, 1.60, "可"),
    ("复杂的 transformer block", 25, 7, 18, 1.0, 5.0, 1.80, "分步融"),
]
for c in combos:
    out.append(f"  {c[0]:22s} {c[1]:3d}      {c[2]:3d}      {c[3]:3d}     {c[6]:.2f}  {c[7]}")
res("\n".join(out))
mea("""结论:
  - 简单组合 (Linear+ReLU): 强推, 收益稳定
  - 复杂组合 (MHA+Softmax): 强推, 收益大
  - 反向组合 (Concat+Split): 不融, 没收益
  - 超复杂 (transformer block): 分步融, 不要 1 个核
工程经验:
  1. 收益 > 1.5x 才值得做
  2. 维护成本高 (需精度对齐 + 性能回归)
  3. 团队能力: 1 人能写 1 个 / 月
  4. 收益 × 频率 = 总收益 (选 hot path)""")
PYEOF

echo ""
echo "############################################################"
cat <<'EOF'
【整体总结】
- 小白:融合快, 因为省 kernel 启动 + 省 HBM 读写 + 省调度空隙 + 缓存复用;
  但不是所有都适合融: 形状差异大、精度要求高、调试期 不融;
  决策树: 性能瓶颈 + 紧邻 + shape 匹配 才融, 收益 > 1.5x 才做。
- 熟手:4 个收益来源的优先级: kernel 启动 > HBM 读写 > 调度 > 复用;
  反模式: 强制全模型融合, 简单 1+1 融, 形状 mismatch 强融;
  实战流程: 不融跑通 -> profile hot op -> 写融合 -> 测精度 -> A/B -> 上线;
  复杂融合 (transformer block) 分步融, 不要 1 个核搞定。
【进阶】在 1 个真实模型上 profile 找 hot op 5 个, 评估每个的融合收益,
  写 1 个融合算子 (推荐 Linear+LayerNorm), 完整走 不融 -> 融 -> 对比 流程,
  量化收益 (性能 + 显存 + 精度), 写报告。
EOF
echo "############################################################"
