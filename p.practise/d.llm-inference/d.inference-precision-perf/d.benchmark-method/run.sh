#!/bin/bash
# ============================================================
# 实验: d.benchmark-method
# 说明: ais-bench、压测脚本、指标采集
# 模块: p.practise 第一性原理学习实验
# ============================================================
# 【第一性原理】
# LLM 推理压测三件套:
#   1. 吞吐量: tokens/s, requests/s
#   2. 延迟: TTFT (首字), TPOT (每字), 总延迟
#   3. 资源: GPU 利用率, 显存占用, 功耗
# 工具:
#   - vLLM benchmark (官方)
#   - 启智 / ais-bench (国内)
#   - wrk / vegeta (通用 HTTP)
#   - locust (Python)
#   - guidance-bench (HF)
# 方法学:
#   - Warmup: 5-10 请求预热 (避免冷启)
#   - 持续时间: 至少 5 分钟
#   - 多场景: 短/中/长 prompt + 短/中/长生成
# ============================================================
set -euo pipefail
echo "############################################################"
echo "# 实验: d.benchmark-method | LLM 压测方法学:吞吐/延迟/资源"
echo "############################################################"

python3 <<'PYEOF'
def hdr(n,t,total): print(f"\n{'='*60}\n【步骤 {n}/{total}】{t}\n{'='*60}")
def why(s): print("\n--- 做什么 & 为什么 ---\n  "+s.replace("\n","\n  "))
def res(s): print("\n--- 结果 ---\n  "+s.replace("\n","\n  "))
def mea(s): print("\n--- 解读 ---\n  "+s.replace("\n","\n  "))
TOTAL = 4

# --- 1. 压测维度 ---
hdr(1,TOTAL,"压测要看的 4 个维度")
why("""LLM 服务压测不是单一指标:""")
res("""维度              指标                反映什么
  吞吐              tokens/s           整体服务能力
  吞吐              requests/s         业务请求能力
  延迟 (TTFT)       P50/P99 首字时间    实时性
  延迟 (TPOT)       P50/P99 每字时间    流式顺滑
  资源              GPU 利用率          算力使用
  资源              显存峰值            服务承载上限
  资源              功耗                运营成本""")
mea("""漏一项都可能误判:
  - 吞吐高但 TPOT P99 spike → 用户体验差
  - GPU 利用率 50% 但延迟低 → 资源浪费
  - 显存峰值接近 OOM → 扩容困难
  - 功耗异常 → 可能功耗墙限制性能""")

# --- 2. 主流压测工具 ---
hdr(2,TOTAL,"主流 LLM 压测工具对比")
why("""选对工具,事半功倍:""")
res("""工具               适用               特点
  vLLM bench         vLLM 服务         官方, 集成度最高
  guidellm           任意 OpenAI API   详细 P50/P99, 易用
  ais-bench          国产/自研         适配国内大模型
  wrk                通用 HTTP         简单粗暴
  locust             通用 HTTP         Python, 可编程
  vegeta             通用 HTTP         Go, 简单
  llm-perf           HF                多模型对比""")
mea("""推荐组合:
  - 上线前: vLLM bench + guidellm 双跑
  - 容量规划: locust 模拟真实流量
  - 国产/昇腾: ais-bench""")

# --- 3. 压测方法学 ---
hdr(3,TOTAL,"压测方法学:7 个注意事项")
why("""为什么压测结果不可信?多半是方法不对:""")
res("""注意项                    错误做法            正确做法
  Warmup                  跳过                  至少 5-10 请求
  请求长度                全相同                短/中/长 mix
  持续时间                30 秒                 5-30 分钟
  并发策略                突增                  渐进 + 稳态
  数据集                  随机                  真实业务采样
  SLO 评估                看平均                P99 + 长尾
  监控                    只看 GPU              + 延迟 + 业务""")
mea("""常见误判:
  - 没 warmup → 第一次请求慢,平均拉高
  - 请求都短 → 测不到长 prompt 的 prefill 慢
  - 时间太短 → 测不到长尾
  - 突增并发 → 测的是瞬时,不是稳态
  - SLO 用平均 → 长尾用户被牺牲""")

# --- 4. 报告模板 ---
hdr(4,TOTAL,"压测报告模板")
why("""一份合格的 LLM 压测报告:""")
res("""压测报告 - [日期] - [模型] - [硬件]
================================
1. 环境
   模型:        LLaMA-3-8B-Instruct (INT4 GPTQ)
   硬件:        1x A100 80G
   框架:        vLLM 0.5
   配置:        --max-num-seqs 256 --enable-chunked-prefill

2. 工作负载
   prompt 长度:   100/500/2000/8000 token 各 25%
   生成长度:      50/200/500/2000 token 各 25%
   并发:          1/8/32/64/128
   持续:          10 分钟/配置

3. 结果 (P50 / P99)
   并发=32:
     吞吐:        3200 tok/s
     TTFT:        80ms / 200ms
     TPOT:        30ms / 80ms
     GPU 利用率:   78%
     显存峰值:     62 GB

4. 结论
   - 并发 ≤ 64 SLO 全达标
   - 并发 = 128 时 TPOT P99 接近上限
   - 建议:生产部署并发上限 64, 留 30% buffer
   - 风险:长 prompt (8K) TTFT 偶发 spike 需关注""")
mea("""模板核心要素:
  - 环境必须详细(后人复现)
  - 工作负载要 mix,不要全短或全长
  - 结论要给\"建议上限\" + \"风险点\"
  - 对比 baseline 才有意义(对比 FP16 / 对比 v0.4)""")
PYEOF

echo ""
echo "############################################################"
cat <<'EOF'
【整体总结】
- 小白:LLM 压测看 4 维度(吞吐/延迟/资源/业务);warmup + 长测试时间 +
  多场景负载 + P99 SLO 才有意义;vLLM bench 一键跑。
- 熟手:guidellm / locust 进阶做容量规划;压测报告要含环境+workload+
  结论+建议上限;横向对比(FP16 vs INT4, v0.4 vs V1)用同一脚本。
【进阶】用 locust 录制真实流量 1 小时回放,做影子测试;用 shadow traffic
  对比新旧模型/新配置。
EOF
echo "############################################################"
