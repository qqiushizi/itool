# ============================================================
# 实验: c.diffusion-basics
# 说明: 前向加噪/反向去噪、DDPM 直觉、U-Net
# 模块: p.practise/b.model-architectures  模型架构
# ============================================================
# 【第一性原理】
# 扩散模型:前向过程逐步往数据加高斯噪声,直到变成纯噪声;反向过程训练一个网络(U-Net)
# 学会"从噪声里一步步去噪"还原数据。关键公式:x_t=√ᾱ_t·x_0+√(1-ᾱ_t)·ε,ᾱ_t 随 t 递减。
# 训练目标:给噪声图和 t,让网络预测噪声 ε(而非直接预测 x_0),简单稳定。
# 生成:从纯噪声开始,反复"预测噪声→减去一小步"直到还原。本实验模拟前向加噪过程与信噪比衰减。
# ============================================================
set -euo pipefail
if ! python3 -c "import numpy" 2>/dev/null; then
  echo "未检测到 numpy,正在安装..."; python3 -m pip install --quiet numpy || { echo "请手动: pip install numpy"; exit 1; }
fi
echo "============================================================"
echo " 实验: 扩散模型 / 前向加噪 / DDPM / U-Net 去噪"
echo "============================================================"
python3 <<'PY'
import numpy as np
np.set_printoptions(precision=4, suppress=True)
rng=np.random.default_rng(0)
# 线性 β 调度,T 步前向加噪
T=20; betas=np.linspace(0.001,0.4,T); alphas=1-betas; abar=np.cumprod(alphas)
x0=np.array([1.0,-1.0,0.5,2.0])   # 一个"数据点"
print("【1】前向加噪:x_t=√ᾱ_t·x_0 + √(1-ᾱ_t)·ε,ᾱ_t 随 t 递减")
for t in [0,5,10,15,19]:
    eps=rng.standard_normal(x0.shape)
    xt=np.sqrt(abar[t])*x0+np.sqrt(1-abar[t])*eps
    print(f"  t={t:>2}: ᾱ={abar[t]:.4f}  信号系数√ᾱ={np.sqrt(abar[t]):.3f}  噪声系数√(1-ᾱ)={np.sqrt(1-abar[t]):.3f}  x_t={xt.round(3).tolist()}")
print("  解读:t 越大,原数据 x_0 的权重越小、噪声权重越大;t=T 时几乎纯噪声。前向是固定的(不需要学)。")

# 2 信噪比
print("\n【2】信噪比 SNR=ᾱ/(1-ᾱ) 随 t 衰减:")
for t in [0,5,10,15,19]:
    snr=abar[t]/(1-abar[t])
    print(f"  t={t:>2}: SNR={snr:.3f}{'  (信号主导)' if snr>1 else '  (噪声主导)'}")
print("  解读:早期 SNR 高(还能看出原图),晚期 SNR 低(纯噪声);反向去噪就是从低 SNR 往高 SNR 走。")

# 3 训练目标 & 反向直觉
print("\n【3】训练目标 & 反向生成(直觉):")
print("  训练:随机取 t 和噪声 ε,加噪得 x_t,让 U-Net 预测 ε(预测噪声,不是预测原图)。")
print("  生成:从 x_T≈纯噪声出发,反复 预测ε̂→ x_{t-1}=去一步噪声,直到 x_0。")
print("  U-Net:编码器降分辨率抓语义+解码器升分辨率还细节+跳连保留细节,适合图像去噪。")
print("  解读:扩散把'生成'转化成'去噪'这个好学的任务;每步只去一点点噪声,累积还原出清晰图像。")
PY
echo "============================================================"
cat <<'EOF'
【结论与进阶】
- 小白:扩散=前向逐步加噪(固定) + 反向训练去噪网络;前向 x_t=√ᾱ·x_0+√(1-ᾱ)·ε;反向从纯噪声一步步去噪还原图。
- 熟手:预测 ε 而非 x_0 使训练目标和方差简单稳定;β 调度影响生成质量(余弦调度优于线性);
  U-Net 的跳连是去噪保细节的关键;采样可加速(DDIM、一致性模型);文生图靠条件注入(text cross-attn)。
- 延伸:把 β 调度换成余弦看 ᾱ 曲线;增加 T 看每步噪声更小、生成更稳。
EOF
echo "============================================================"
