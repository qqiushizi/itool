#!/bin/bash
# ============================================================
# 实验: c.backprop-from-scratch
# 说明: 计算图 + 手算反向传播
# 模块: p.practise/a.ai-fundamentals  AI 基础
# ============================================================
# 【第一性原理】
# 神经网络是一个复合函数 L(θ)。求最优 θ 要梯度 ∇L,而对复合函数求导的通用工具是链式法则。
# 反向传播 = 把网络拆成计算图节点,前向算值、反向沿图把梯度从输出逐节点乘回来。
# 每个节点只需知道"我的输出对输入的局部导数",全局梯度由链式自动拼好。
# 本实验手写一个 2 层小网的前向+反向,并用有限差分数值梯度验证手算正确。
# ============================================================
set -euo pipefail
if ! python3 -c "import numpy" 2>/dev/null; then
  echo "未检测到 numpy,正在安装..."; python3 -m pip install --quiet numpy || { echo "请手动: pip install numpy"; exit 1; }
fi
echo "============================================================"
echo " 实验: 计算图 / 反向传播手算 / 数值梯度验证"
echo "============================================================"
python3 <<'PY'
import numpy as np
np.set_printoptions(precision=5, suppress=True)
def sig(z): return 1/(1+np.exp(-z))
def block(i,t,title,why,res,mean):
    print(f"\n{'='*58}\n【步骤 {i}/{t}】{title}\n{'='*58}")
    print(f"--- 做什么 & 为什么 ---\n  {why}\n--- 结果 ---\n  {res}\n--- 结果解读 ---\n  {mean}")
T=4
# 计算图: x -> z1=w1*x+b1 -> a1=sig(z1) -> z2=w2*a1+b2 -> a2=sig(z2) -> L=0.5(a2-t)^2
x,t=1.5,1.0; w1,b1,w2,b2=0.6,-0.3,1.2,0.1
theta=np.array([w1,b1,w2,b2])

# 1 画计算图(文字)
block(1,T,"计算图:把网络拆成节点",
 "目标函数 L=0.5*(σ(w2*σ(w1*x+b1)+b2)-t)^2。拆成 6 个节点串成一条链。",
 "节点链:\n  x ──(×w1,+b1)──▶ z1 ──σ──▶ a1 ──(×w2,+b2)──▶ z2 ──σ──▶ a2 ──(−t,²,×0.5)──▶ L",
 "每个节点只负责一个简单运算;求全局梯度时,沿链把各节点的局部导数乘起来即可。\n  → 这就是'计算图'思想:复杂函数=简单节点的组合,自动求导靠它来机械化处理。")

# 2 前向(记录中间值)
z1=w1*x+b1; a1=sig(z1); z2=w2*a1+b2; a2=sig(z2); L=0.5*(a2-t)**2
block(2,T,"前向:从左到右算出每个节点的值",
 "代入 x=1.5,t=1,w1=0.6,b1=-0.3,w2=1.2,b2=0.1,逐节点算。",
 f"z1={z1:.4f}, a1={a1:.4f}\n  z2={z2:.4f}, a2={a2:.4f}\n  L={L:.5f}",
 "前向把所有中间值算出来缓存好,反向时直接用。a2≈0.74 离目标 1 还差 0.26,L 就是这个差的平方(一半)。")

# 3 反向:链式逐节点
dLda2=a2-t                           # dL/da2
dLdz2=dLda2*a2*(1-a2)                # ×σ'
dLdw2=dLdz2*a1; dLdb2=dLdz2          # ×∂z2/∂w2=a1, ∂z2/∂b2=1
dLda1=dLdz2*w2                       # ×∂z2/∂a1=w2
dLdz1=dLda1*a1*(1-a1)                # ×σ'
dLdw1=dLdz1*x; dLdb1=dLdz1           # ×∂z1/∂w1=x, ∂z1/∂b1=1
grads=np.array([dLdw1,dLdb1,dLdw2,dLdb2])
block(3,T,"反向:从右到左,局部导数逐节点乘回来",
 "从 L 出发:先 dL/da2=(a2-t);每过一节点乘上该节点的局部导数,得到对每个参数的梯度。",
 f"dL/da2={dLda2:.4f} → dL/dz2={dLdz2:.4f}\n  dL/dw2={dLdw2:.4f}, dL/db2={dLdb2:.4f}\n  dL/da1={dLda1:.4f} → dL/dz1={dLdz1:.4f}\n  dL/dw1={dLdw1:.4f}, dL/db1={dLdb1:.4f}",
 "梯度从输出端往输入端'流',每流过一节点乘一次局部导数——这就是链式法则。\n  → 每层只需缓存前向的中间值,就能算出自己的梯度,无需关心别的层(模块化)。")

# 4 数值梯度验证
e=1e-6
def loss(p):
    W1,B1,W2,B2=p
    return 0.5*(sig(sig(x*W1+B1)*W2+B2)-t)**2
ng=np.zeros_like(theta)
for k in range(4):
    p=theta.copy(); p[k]+=e; lp=loss(p)
    p[k]-=2*e; lm=loss(p); ng[k]=(lp-lm)/(2*e)
err=np.abs(grads-ng).max()
block(4,T,"数值梯度验证:有限差分对拍",
 "对每个参数扰动 ±ε 算 (L(θ+ε)-L(θ-ε))/2ε,得到数值梯度,与手算解析梯度对比。",
 f"解析梯度 = {grads.round(5).tolist()}\n  数值梯度 = {ng.round(5).tolist()}\n  最大误差 = {err:.2e}",
 "两者几乎相同(误差≈1e-8)→手算的反向传播完全正确。\n  → 工程里 autograd 也是这样'自动链式';会用数值梯度对拍,是验证自定义层/损失正确性的标准手段。")
PY
echo "============================================================"
cat <<'EOF'
【结论与进阶】
- 小白:网络=计算图;前向从左到右算值,反向从右到左把梯度逐节点乘回来(链式法则);
  数值梯度对拍能验证你手写的导数对不对。
- 熟手:反向传播复杂度 O(参数量),一次前向+一次反向就能拿到全部梯度,比数值法快得多;
  autograd 本质就是动态构建计算图并按拓扑逆序传播梯度;梯度爆炸/消失源于连乘的局部导数。
- 延伸:把激活换成 ReLU 重算 dL/dw1;把网络加深一层,手推多一个节点的反向公式。
EOF
echo "============================================================"
