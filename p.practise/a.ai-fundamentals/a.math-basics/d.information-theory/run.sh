set -euo pipefail
if ! python3 -c "import numpy" 2>/dev/null; then
  echo "未检测到 numpy,正在安装..."; python3 -m pip install --quiet numpy || { echo "请手动: pip install numpy"; exit 1; }
fi
echo "############################################################"
echo "# 实验 4: 信息量 / 熵 / KL 散度 / 交叉熵"
echo "# 每步: 【做什么&为什么】→【结果】→【结果解读】"
echo "############################################################"

python3 <<'PY'
import numpy as np
def H(p):
    p=np.asarray(p,float); p=p[p>0]; return -np.sum(p*np.log2(p))
def KL(p,q):
    p=np.asarray(p,float); q=np.asarray(q,float); m=(p>0)&(q>0)
    return np.sum(p[m]*np.log2(p[m]/q[m]))
def CE(p,q):
    p=np.asarray(p,float); q=np.asarray(q,float); m=p>0
    return -np.sum(p[m]*np.log2(q[m]))

def step(n,t,title): print(f"\n{'='*60}\n【步骤 {n}/{t}】{title}\n{'='*60}")
def why(t):
    print("\n--- 我们要做什么 & 为什么要这么做 ---")
    for l in t.strip().splitlines(): print("  "+l)
def res(t):
    print("\n--- 运行结果 ---")
    for l in t.strip().splitlines(): print("  "+l)
def meaning(t):
    print("\n--- 结果解读(这说明了什么)---")
    for l in t.strip().splitlines(): print("  "+l)
T=4

# ============================================================
step(1,T,"信息量:从投硬币说起")
why("""
对不同概率的事件算信息量 -log2(p),看"越罕见越意外"。
为什么:信息量衡量"得知某事件发生时的意外程度"。必然事件(p=1)毫不意外=0信息;
极小概率事件一旦发生=巨大信息量。这是信息论的最基本量。""")
out=[]
for p in [1.0,0.5,0.25,0.125,0.01]:
    out.append(f"  P={p:<6} -> 信息量 = {-np.log2(p):.2f} 比特")
res("\n".join(out))
meaning("""
公平硬币(p=0.5)每次给 1 比特;连续3次正面(p=0.125)给 3 比特。
必然事件(p=1)给 0 比特(毫无意外)。
→ "比特"不只是存储单位,更是"消除不确定性"的度量。""")

# ============================================================
step(2,T,"熵:一个分布的平均不确定性")
why("""
对三种硬币分布算熵:公平、偏斜、必然。
为什么:熵=分布的"平均信息量"=不确定性。分布越均匀越难猜,熵越大;
越确定熵越小。决策树正是用熵选"最能降低不确定性"的分裂点。""")
out=[]
for name,p in [("公平硬币",[0.5,0.5]),("偏斜硬币",[0.9,0.1]),("必然事件",[1.0,0.0])]:
    out.append(f"  {name}  P={p}  熵={H(p):.3f} bit")
res("\n".join(out))
meaning("""
公平硬币熵=1(最大,最不确定);偏斜硬币熵=0.47(更易猜);
必然事件熵=0(完全确定)。
→ 熵越大=越混乱/越难预测。模型输出如果熵很高,说明它"拿不准"。""")

# ============================================================
step(3,T,"KL 散度:衡量预测分布偏离真实的程度")
why("""
固定真实分布 p,用不同预测 q 算 KL(p||q),并验证非对称、非负。
为什么:KL 衡量"用 q 编码 p 时多花的额外比特"。q 越接近 p,KL 越小;q=p 时为 0。
知识蒸馏就是让 student 分布(KL)逼近 teacher。""")
p=[0.7,0.3]; out=[]
for q in [[0.7,0.3],[0.6,0.4],[0.5,0.5],[0.9,0.1]]:
    out.append(f"  p={p}, q={q}  ->  KL(p||q)={KL(p,q):.4f}")
out.append(f"  反向 KL(q||p) 对 q=[0.5,0.5]={KL([0.5,0.5],p):.4f}  (与正向不同=>非对称)")
res("\n".join(out))
meaning("""
q=p 时 KL=0(完美);q 越偏 KL 越大。正向反向 KL 不同(非对称)。
→ KL>=0 恒成立,是衡量"两分布差异"的标准工具。
→ 蒸馏损失 = KL(student||teacher),让小模型学大模型的"软概率分布"。""")

# ============================================================
step(4,T,"交叉熵 = 熵 + KL:分类为什么用它做损失")
why("""
真实标签是 one-hot(只一类为1),用不同预测 q 算交叉熵。
为什么:交叉熵 = H(p) + KL(p||q)。one-hot 的 H(p)=0,此时交叉熵=KL。
最小化交叉熵 = 让预测分布逼近真实标签。这就是分类/语言模型损失的本质。""")
p=[1.0,0.0,0.0]; out=[f"  真实标签 p={p} (one-hot, H(p)={H(p):.3f})"]
for q in [[0.7,0.2,0.1],[0.4,0.3,0.3],[0.34,0.33,0.33]]:
    out.append(f"  预测 q={q}  交叉熵={CE(p,q):.4f}  = H(p)+KL = {H(p):.3f}+{KL(p,q):.4f}")
res("\n".join(out))
meaning("""
预测越集中在正确类(0.7),交叉熵越小(0.51);越均匀(0.34),交叉熵越大(1.56)。
→ 训练分类模型 = 最小化交叉熵 = 让预测逼近真实 one-hot。
→ 语言模型 loss 就是 token 级交叉熵均值;perplexity = 2^交叉熵,越低越准。
→ 试一试:运行 demo.py --true 1 --pred 0.01,看"自信地错"的交叉熵有多大。""")
PY

echo ""
echo "############################################################"
cat <<'EOF'
【整体总结】
- 小白:信息量衡量"意外",熵衡量"不确定性",KL 衡量"两分布差多少",
  交叉熵是分类的标准损失(预测越准交叉熵越小)。
- 熟手:语言模型 loss=token级交叉熵均值(perplexity=2^交叉熵);KL 用于蒸馏、VAE 的 ELBO。

【动手体验】python3 demo.py --true 1 --pred 0.01  看"自信地错"的交叉熵有多大
