# ============================================================
# 【第一性原理】
# 线性回归:用一条直线 y=wx+b 拟合数据。"最好"=误差平方和最小(最小二乘)。
# 三种等价解法:正规方程(闭式)、梯度下降(迭代)、最小二乘(SVD)。
# 这是理解"优化"与"闭式解"关系的最佳起点,也是深度学习优化的祖师爷。
# ============================================================
set -euo pipefail
if ! python3 -c "import numpy" 2>/dev/null; then
  echo "未检测到 numpy,正在安装..."; python3 -m pip install --quiet numpy || { echo "请手动: pip install numpy"; exit 1; }
fi
echo "############################################################"
echo "# 实验: 线性回归 三种解法对比"
echo "# 每步: 【做什么&为什么】→【结果】→【结果解读】"
echo "############################################################"

python3 <<'PY'
import numpy as np
rng = np.random.default_rng(7)
def step(n,t,title): print(f"\n{'='*60}\n【步骤 {n}/{t}】{title}\n{'='*60}")
def why(t):
    print("\n--- 我们要做什么 & 为什么要这么做 ---")
    for l in t.strip().splitlines(): print("  "+l)
def res(t):
    print("\n--- 运行结果 ---")
    for l in t.strip().splitlines(): print("  "+l)
def meaning(t):
    print("\n--- 结果解读(这说明了什么)---")
    for l in t.strip().splitlines(): print("  "+l)
T=4

# ============================================================
step(1,T,"造数据:真实关系 y=2x+1+噪声")
why("""
生成 50 个点,真实规律 y=2x+1,叠加高斯噪声。
为什么:真实数据 = 规律 + 噪声。线性回归的任务是从带噪声的数据里
"反推"出那条规律。我们已知真值(2,1),所以能检验各解法准不准。""")
n=50; x=rng.uniform(0,10,n); y=2.0*x+1.0+rng.standard_normal(n)*2.0
X=np.column_stack([x,np.ones(n)])
res(f"""数据点 {n} 个, 真实参数 w=2, b=1, 含高斯噪声
  前5个点: {[(round(x[i],2),round(y[i],2)) for i in range(5)]}""")
meaning("""
每个点是 (x, y)。肉眼看不出规律,但背后有 y=2x+1 的直线 + 随机扰动。
回归要从这堆散点里"猜"出斜率2和截距1。噪声越大越难猜。""")

# ============================================================
step(2,T,"解法一:正规方程(闭式解)")
why("""
用 w=(X^T X)^{-1} X^T y 一步算出解析解。
为什么:这是线性回归的"标准答案公式",数学上精确。
但它要矩阵求逆——特征多时又慢又数值不稳定,这是后来改用梯度下降的原因。""")
w_norm=np.linalg.inv(X.T@X)@X.T@y
res(f"  正规方程: w={w_norm[0]:.4f}, b={w_norm[1]:.4f}  (真实 w=2, b=1)")
meaning(f"""
算出 w≈{w_norm[0]:.2f}、b≈{w_norm[1]:.2f},接近真值2和1(因噪声有偏差)。
正规方程一步到位,但要求 X^T X 可逆。特征维度 d 大时求逆是 O(d^3),扛不住。""")

# ============================================================
step(3,T,"解法二:梯度下降(迭代逼近)")
why("""
从 w=0 开始,每步沿 loss 对 w 的负梯度走一小步,迭代2000次。
为什么:梯度下降是深度学习优化的核心。它不需要矩阵求逆,
大数据/高维下更实用。理解它=理解神经网络怎么训练。""")
w=np.zeros(2); lr=0.001; out=[]
for i in range(2000):
    pred=X@w; grad=X.T@(pred-y)/n; w-=lr*grad
    if i in (0,99,999,1999):
        loss=np.mean((pred-y)**2)
        out.append(f"  步{i+1:>4}: w={w[0]:.4f}, b={w[1]:.4f}, MSE={loss:.4f}")
res("\n".join(out))
meaning("""
loss 从大降到约3,参数逐步逼近真值。梯度下降虽慢但稳,且不挑矩阵条件。
→ 所有深度学习训练都是这个套路:算梯度、走一步、重复。""")

# ============================================================
step(4,T,"解法三:最小二乘(lstsq)+ 三法对比")
why("""
用 numpy.lstsq(SVD 实现)求解,并与前两法对比。
为什么:lstsq 即使矩阵不可逆/秩亏也能给出最优近似解,数值最稳。
三法解的是同一问题,结果应一致——验证殊途同归。""")
w_lsq,*_=np.linalg.lstsq(X,y,rcond=None)
res(f"""  最小二乘(lstsq): w={w_lsq[0]:.4f}, b={w_lsq[1]:.4f}
  正规方程 = {w_norm.round(4).tolist()}
  梯度下降 = {w.round(4).tolist()}
  最小二乘 = {w_lsq.round(4).tolist()}
  正规方程 vs 最小二乘 最大差异 = {np.max(np.abs(w_norm-w_lsq)):.2e}""")
meaning("""
正规方程和最小二乘几乎完全一致(差异≈0,都是闭)。
梯度下降因迭代次数/学习率有限,略偏离但方向对。
→ 工程首选最小二乘(数值稳);深度学习用梯度下降(可扩展、可求导)。""")
PY

echo ""
echo "############################################################"
cat <<'EOF'
【整体总结】
- 小白:线性回归=找让误差最小的直线;正规方程一步算、梯度下降慢慢凑、最小二乘最稳,三者同源。
- 熟手:正规方程 O(d^3) 只适合小特征;梯度下降是深度学习优化鼻祖;最小二乘用 SVD 能处理秩亏。
【动手体验】python3 demo.py --noise 5 --features 20  看噪声和特征数如何影响各解法
